"""Сокращения во фрагментах (georag/chat/abbreviations.py): список в задание и выдуманные
расшифровки в ответе."""

from __future__ import annotations

from georag.chat import abbreviations as A

SOURCES = [
    {"n": 1, "text": "ГЗН приурочена к градациям катагенеза РОВ от конца ПК3 до конца МК2. "
                     "Перспективы связаны с нефтегазоносной системой прогиба ДМНГ."},
    {"n": 2, "text": "Выделены структурно-литологические ловушки (СЛЛ) и литологически "
                     "ограниченные ловушки (ЛЛ). ФЕС пород изучены по керну; аномалии "
                     "указывают на КДП."},
    {"n": 3, "text": "ГЕОЛОГИЯ РАЙОНА РАБОТ Район сложен осадочными породами."},
]  # fmt: skip


def test_abbreviations_of_fragments_known_and_unknown() -> None:
    known, unknown = A.known_and_unknown(SOURCES)
    assert known["РОВ"] == "рассеянное органическое вещество"
    assert known["СЛЛ"] == "структурно-литологические ловушки"  # расшифрована во фрагменте
    assert known["ЛЛ"] == "литологически ограниченные ловушки"
    assert "ДМНГ" in unknown and "КДП" in unknown
    assert "РАЙОНА" not in unknown and "РАБОТ" not in unknown  # заголовок прописными


def test_note_lists_both_kinds() -> None:
    text = A.note(SOURCES)
    assert "РОВ — рассеянное органическое вещество" in text
    assert "ДМНГ" in text and "как есть" in text
    assert A.note([{"n": 1, "text": "Березит — метасоматическая порода."}]) == ""


def test_wrong_expansion_before_abbreviation_removed() -> None:
    answer = (
        "ГЗН приурочена к градациям катагенеза органического вещества (РОВ) [1]. Отмечены "
        "повышенные концентрации растительных остатков (РОВ) [1]. Перспективы связаны с "
        "прогибом Дальневосточной нефтегазоносной провинции (ДМНГ) [1]."
    )
    text, fixed = A.fix(answer, SOURCES)
    assert "градациям катагенеза РОВ [1]" in text
    assert "повышенные концентрации РОВ [1]" in text
    # Что считать началом выдуманной расшифровки, неясно — текст не трогается.
    assert "Дальневосточной нефтегазоносной провинции (ДМНГ)" in text
    assert len(fixed) == 2


def test_right_expansions_stay() -> None:
    answer = (
        "Главная зона нефтеобразования (ГЗН) приурочена к градациям катагенеза рассеянного "
        "органического вещества (РОВ) [1]. Выделены структурно-литологические ловушки (СЛЛ) "
        "[2]. Породы содержат органические вещества (ОВ) [1]."
    )
    assert A.fix(answer, SOURCES) == (answer, [])


def test_expansion_in_brackets_after_abbreviation() -> None:
    answer = (
        "Зависимостей ФЕС (фазовые эффективные свойства) не установлено [2]. Аномалии "
        "указывают на КДП (контур давления) [2]. ОВ (для газоматеринских пород) — гумусовое [1]. "
        "По ГИС (геофизическим исследованиям скважин) выделены коллекторы [2]."
    )
    text, fixed = A.fix(answer, SOURCES)
    assert "ФЕС (фильтрационно-ёмкостные свойства) не установлено" in text
    assert "указывают на КДП [2]" in text
    assert "ОВ (для газоматеринских пород)" in text  # пояснение, а не расшифровка
    assert "ГИС (геофизическим исследованиям скважин)" in text
    assert len(fixed) == 2
