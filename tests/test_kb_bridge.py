# ------------------------------------------------------------- по сети
class _БазаЗнаний(BaseHTTPRequestHandler):
    """Подставная база знаний: по территории с методом пусто, по одной территории — есть."""

    def log_message(self, *args):
        pass

    def _json(self, код, тело):
        данные = json.dumps(тело, ensure_ascii=False).encode("utf-8")
        self.send_response(код)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(данные)))
        self.end_headers()
        self.wfile.write(данные)

    def do_GET(self):
        self._json(200, {"concepts": [{"code": "гидротермальные изменения"}],
                         "territories": ["Билляхская зона"], "methods": ["ASTER"]})

    def do_POST(self):
        запрос = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
        type(self).запросы.append(запрос)
        if запрос["concept"] == "нет такого":
            self._json(400, {"error": "понятия нет в словаре базы знаний"})
        elif запрос.get("method"):
            self._json(200, {"fragments": [], "as_of": "2026-09-21T10:00:00+00:00"})
        else:
            self._json(200, {"fragments": [ЦИТАТА], "as_of": "2026-09-21T10:00:00+00:00"})


@pytest.fixture
def база_знаний():
    _БазаЗнаний.запросы = []
    сервер = ThreadingHTTPServer(("127.0.0.1", 0), _БазаЗнаний)
    threading.Thread(target=сервер.serve_forever, daemon=True).start()
    yield f"http://127.0.0.1:{сервер.server_address[1]}"
    сервер.shutdown()


def test_ослабляет_отбор_пока_не_найдёт(база_знаний):
    территория, метод, фрагменты, as_of = м.статьи_по_понятию(
        база_знаний, "гидротермальные изменения", "ASTER", ("Билляхская зона",), 3)
    assert (территория, метод) == ("Билляхская зона", None)
    assert фрагменты == [ЦИТАТА] and as_of
    первый = _БазаЗнаний.запросы[0]
    assert первый["territory"] == "Билляхская зона" and первый["method"] == "ASTER"
    assert первый["per_doc"] == 1, "на понятие нужны разные статьи, а не абзацы одной"


