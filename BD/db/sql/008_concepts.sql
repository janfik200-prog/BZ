-- Справочник понятий: то, с чем связываются признаки.
-- Запускается от gisadmin после 007_review.sql.
--
-- До этой миграции связь «признак — понятие» ссылалась на понятие простой
-- строкой, и справочника не было: сослаться было не на что, проверить нечем.
-- Здесь появляется сам справочник, а связь получает внешний ключ.

CREATE TABLE kb.concept (
    code         text PRIMARY KEY,          -- имя понятия, оно же ссылка из bridge
    kind         text NOT NULL CHECK (kind IN (
                     'рудоконтролирующий фактор',   -- отвечает за оруднение
                     'условие наблюдения')),        -- отвечает за то, что видно съёмке
    definition   text NOT NULL,
    source       text,                      -- откуда определение
    status       meta.status NOT NULL DEFAULT 'черновик',
    confirmed_by text,
    confirmed_at timestamptz,
    note         text,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE kb.concept IS
    'Понятия, к которым агент привязывает признаки: рудоконтролирующие факторы и условия наблюдения';
COMMENT ON COLUMN kb.concept.kind IS
    'Условие наблюдения — не рудный фактор: отвечает за то, что видит съёмка, а не за оруднение';

CREATE TRIGGER guard_confirmation BEFORE INSERT OR UPDATE ON kb.concept
    FOR EACH ROW EXECUTE FUNCTION meta.guard_confirmation();
CREATE TRIGGER touch_updated_at BEFORE UPDATE ON kb.concept
    FOR EACH ROW EXECUTE FUNCTION meta.touch_updated_at();

GRANT SELECT ON kb.concept TO gis_read;
GRANT SELECT, INSERT, UPDATE ON kb.concept TO gis_agent, gis_human;

