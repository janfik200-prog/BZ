-- 010: чем именно сделан паспорт — отпечаток весов модели.
--
-- Имя модели («gemma4:12b») называет тег в реестре, а не конкретные веса:
-- содержимое тега со временем обновляется, и через полгода «тот же» прогон
-- окажется сделан другой моделью. Для базы, где паспорт — документ с
-- происхождением, этого мало: рядом с именем пишется отпечаток файла весов.
-- У облачной модели отпечатка нет — там версия и есть имя, столбец остаётся
-- пустым.

ALTER TABLE runs.llm_call ADD COLUMN IF NOT EXISTS model_digest text;

COMMENT ON COLUMN runs.llm_call.model_digest IS
    'Отпечаток весов локальной модели (sha256). Пусто у облака и у средства '
    'разработки: там версия модели называется именем.';
