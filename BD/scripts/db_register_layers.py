def завести_лицензии(conn) -> dict[str, int]:
    """Черновики лицензий; подтверждённые человеком не трогаем."""
    номера: dict[str, int] = {}
    for код, данные in ЛИЦЕНЗИИ.items():
        conn.execute(
            """INSERT INTO meta.license (code, title, url, allows_redistribution)
               VALUES (%s, %s, %s, %s)
               ON CONFLICT (code) DO UPDATE SET
                   title = EXCLUDED.title, url = EXCLUDED.url,
                   allows_redistribution = EXCLUDED.allows_redistribution
               WHERE meta.license.status = 'черновик'""",
            (код, данные["title"], данные["url"], данные["redistribution"]),
        )
        номера[код] = conn.execute(
            "SELECT id FROM meta.license WHERE code = %s", (код,)
        ).fetchone()[0]
    return номера


def признаки_слоя(conn, источник: Источник) -> list[int]:
    """Номера признаков всех сборок, полученных из этого слоя."""
    if источник.признаки:
        строки = conn.execute(
            "SELECT id FROM data.feature WHERE code = ANY(%s)", (list(источник.признаки),)
        ).fetchall()
    elif источник.группы:
        строки = conn.execute(
            "SELECT id FROM data.feature WHERE group_code = ANY(%s)", (list(источник.группы),)
        ).fetchall()
    else:
        return []
    return [номер for (номер,) in строки]


def покрытие_признаков(conn, номера: list[int]) -> float | None:
    """Среднее покрытие признаков слоя на основном листе — измерение, а не оценка."""
    if not номера:
        return None
    строка = conn.execute(
        """SELECT avg(p.coverage_frac)
             FROM data.feature f
             JOIN meta.feature_passport p ON p.feature_id = f.id
            WHERE f.id = ANY(%s) AND f.definition->>'сборка' = %s""",
        (номера, СБОРКА_ПОКРЫТИЯ),
    ).fetchone()
    return None if строка is None or строка[0] is None else float(строка[0])


def связать_с_признаками(conn, run_id: int, layer_id: int, номера: list[int]) -> int:
    """Рёбра графа происхождения «слой -> признак»: откуда признак взялся на самом деле.

    Ребро «файл сборки -> признак» пишется при загрузке датасета и говорит только,
    из какой таблицы значение прочитано. Здесь фиксируется источник.
    """
    новые = [
        номер for номер in номера
        if not conn.execute(
            """SELECT 1 FROM meta.derivation
                WHERE source_kind = 'слой' AND source_id = %s
                  AND target_kind = 'признак' AND target_id = %s LIMIT 1""",
            (layer_id, номер),
        ).fetchone()
    ]
    if not новые:
        return 0
    op_id = conn.execute(
        """INSERT INTO meta.operation (kind, script, git_commit, params, run_id)
           VALUES ('источник признака', 'scripts/db_register_layers.py', %s,
                   '{}'::jsonb, %s) RETURNING id""",
        (ingest.git_commit(), run_id),
    ).fetchone()[0]
    for номер in новые:
        conn.execute(
            """INSERT INTO meta.derivation
                   (operation_id, source_kind, source_id, target_kind, target_id)
               VALUES (%s, 'слой', %s, 'признак', %s)""",
            (op_id, layer_id, номер),
        )
    return len(новые)


def контур_запроса(conn) -> str:
    """Прямоугольник, по которому качались открытые съёмки: охват обеих сеток проекта."""
    return conn.execute(
        "SELECT ST_AsText(ST_Envelope(ST_Extent(geom)::geometry)) FROM data.cell"
    ).fetchone()[0]


