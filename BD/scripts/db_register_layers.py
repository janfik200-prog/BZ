"""Регистрация слоёв-источников в базе: data.source_layer + черновики паспортов.

Запуск:
    python scripts/db_register_layers.py            — записать в базу
    python scripts/db_register_layers.py --проверка — посчитать и показать, без записи

Что делает по каждому источнику:
* собирает набор файлов слоя (шейп — вместе с .dbf/.shx/.pj4, сетка ГИС Интегро —
  вместе со всеми .property), считает суммарный объём и общую контрольную сумму;
* определяет контур: для векторов — выпуклая оболочка объектов в WGS84, для сеток
  ГИС Интегро — рамка сетки, для открытых съёмок — прямоугольник запроса
  (охват обеих сеток проекта; фактическое покрытие — отдельное поле паспорта);
* пишет запись в `data.source_layer` и черновик паспорта `meta.layer_passport`;
* заводит черновик лицензии в `meta.license`.

Покрытие в паспорте слоя — не оценка, а измерение: среднее покрытие тех признаков
основной сборки, которые из этого слоя получены. Пустое покрытие значит, что
признаков из слоя в базе пока нет.

Лицензию и геологический смысл подтверждает человек: агент ставит только статус
«черновик», статус «подтверждён» ему запрещён триггером meta.guard_confirmation.
"""

