ШЕЙП_РАСШИРЕНИЯ = {".shp", ".shx", ".dbf", ".prj", ".cpg", ".sbn", ".sbx", ".pj4"}


def файлы_слоя(путь: Path) -> list[Path]:
    """Все файлы, из которых слой состоит: шейп — с таблицей атрибутов, сетка — с каналами."""
    основа = путь.stem
    соседи = [
        p for p in путь.parent.iterdir()
        if p.is_file() and (p.name.startswith(f"{основа}.") or p.name.startswith(f"{основа}_"))
    ]
    if путь.suffix.lower() in {".shp"}:
        соседи = [p for p in соседи if p.suffix.lower() in ШЕЙП_РАСШИРЕНИЯ]
    return sorted(соседи, key=lambda p: p.name) or [путь]


def сводка(файлы: list[Path]) -> tuple[str, int]:
    """Общая контрольная сумма набора файлов и суммарный объём в байтах."""
    общая = hashlib.sha256()
    объём = 0
    for файл in файлы:
        общая.update(файл.name.encode("utf-8"))
        общая.update(ingest.checksum(файл).encode("ascii"))
        объём += файл.stat().st_size
    return общая.hexdigest(), объём


def proj4_слоя(путь: Path) -> str | None:
    """Проекция слоя: свой сопроводительный файл, иначе — от соседей по каталогу."""
    свой = data_loader.read_sidecar_proj4(путь)
    if свой:
        return свой
    for сосед in sorted(путь.parent.glob("*_shp.pj4")):
        текст = сосед.read_text(encoding="utf-8", errors="ignore")
        for строка in текст.splitlines():
            if строка.startswith("pj4="):
                return строка[4:].strip()
    return None


def контур_вектора(путь: Path) -> str | None:
    """Выпуклая оболочка объектов слоя в широте-долготе."""
    слой = data_loader.load_layer(путь)
    if слой.empty:
        return None
    if слой.crs is None:
        proj4 = proj4_слоя(путь)
        if proj4 is None:
            return None
        слой = слой.set_crs(CRS.from_proj4(proj4), allow_override=True)
    геометрия = слой.to_crs(4326).geometry
    геометрия = геометрия[геометрия.notna() & ~геометрия.is_empty]
    if геометрия.empty:
        return None
    # Оболочка строится по набору объектов без их объединения: часть слоёв
    # организации содержит самопересекающиеся полигоны, и объединение на них падает.
    return GeometryCollection(list(геометрия.values)).convex_hull.wkt


def контур_сетки(путь: Path) -> tuple[str | None, float | None]:
    """Рамка сетки ГИС Интегро в широте-долготе и её шаг в метрах."""
    сетка = integro_grid.read_pgrid(путь)
    proj4 = integro_grid.read_grid_proj4(путь)
    if proj4 is None:
        return None, сетка.dx
    рамка = box(сетка.x0, сетка.y0,
                сетка.x0 + сетка.pic * сетка.dx, сетка.y0 + сетка.prf * сетка.dy)
    в_градусах = gpd.GeoSeries([рамка], crs=CRS.from_proj4(proj4)).to_crs(4326)
    return в_градусах.iloc[0].wkt, сетка.dx


