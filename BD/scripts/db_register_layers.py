def собрать(источник: Источник) -> dict:
    """Посчитать по источнику всё, что можно измерить, не заглядывая в базу."""
    запись: dict = {
        "checksum": None, "size": None, "footprint": None,
        "resolution": источник.разрешение, "files": [],
    }
    if источник.путь is None:
        return запись
    if not источник.путь.exists():
        raise FileNotFoundError(f"{источник.code}: нет файла {источник.путь}")

    запись["files"] = файлы_слоя(источник.путь)
    запись["checksum"], запись["size"] = сводка(запись["files"])
    if источник.контур == "сетка":
        запись["footprint"], шаг = контур_сетки(источник.путь)
        запись["resolution"] = источник.разрешение or шаг
    else:
        запись["footprint"] = контур_вектора(источник.путь)
    return запись


def main(проверка: bool = False) -> None:
    источники = реестр()
    посчитано = {и.code: собрать(и) for и in источники}

    if проверка:
        for и in источники:
            д = посчитано[и.code]
            объём = "—" if д["size"] is None else f"{д['size'] / 1e6:8.1f} МБ"
            контур = "нет" if д["footprint"] is None else "есть"
            print(f"{и.code:38} {и.kind:7} {объём} файлов {len(д['files']):3} "
                  f"контур {контур}  {и.title[:45]}")
        print(f"\nвсего источников: {len(источники)}")
        return

    with db.connect("gis_agent") as conn:
        with ingest.run(
            conn,
            script="scripts/db_register_layers.py",
            note=f"регистрация слоёв-источников: {len(источники)} шт.",
            model=МОДЕЛЬ,
        ) as run_id:
            лицензии = завести_лицензии(conn)
            прямоугольник = контур_запроса(conn)
            conn.commit()

            для_запроса = 0
            рёбер = 0
            for и in источники:
                д = посчитано[и.code]
                контур = д["footprint"] or (прямоугольник if и.контур == "запрос" else None)
                if и.контур == "запрос":
                    для_запроса += 1
                layer_id = conn.execute(
                    ВСТАВКА_СЛОЯ,
                    (и.code, и.title, и.kind, и.provider, и.url,
                     db.store_ref(и.путь) if и.путь else None,
                     и.формат, и.crs, д["resolution"],
                     и.съёмка[0], и.съёмка[1], контур, д["checksum"], д["size"]),
                ).fetchone()[0]

                номера = признаки_слоя(conn, и)
                покрытие = покрытие_признаков(conn, номера)
                рёбер += связать_с_признаками(conn, run_id, layer_id, номера)
                conn.execute(
                    ВСТАВКА_ПАСПОРТА,
                    (layer_id, лицензии[и.лицензия], и.заметка, и.метод,
                     покрытие, None if покрытие is None else 1.0 - покрытие,
                     ПОЯСНЕНИЕ_КОНТУРА[и.контур], МОДЕЛЬ),
                )
                for файл in д["files"]:
                    ingest.add_input(conn, run_id, файл)
                conn.commit()

                показ = "—" if покрытие is None else f"{покрытие:.3f}"
                print(f"[{layer_id:3}] {и.code:38} файлов {len(д['files']):3} "
                      f"признаков {len(номера):3} покрытие {показ}", flush=True)

            ingest.add_metric(conn, run_id, "слоёв зарегистрировано", len(источники))
            ingest.add_metric(conn, run_id, "слоёв по контуру запроса", для_запроса)
            ingest.add_metric(conn, run_id, "рёбер слой-признак", рёбер)
            conn.commit()
            print(f"\nпрогон #{run_id}: слоёв {len(источники)}, "
                  f"лицензий-черновиков {len(лицензии)}, "
                  f"новых рёбер происхождения {рёбер}")


if __name__ == "__main__":
    main(проверка="--проверка" in sys.argv)
