"""Схема работы агентной базы данных (узлы 3-4 технологической схемы).

Рисует один лист: как данные попадают в базу, где работает агент, где
обязателен человек и что база отдаёт наружу. Сквозные контуры — журнал
прогонов с графом происхождения и реестр пробелов.

Результат: outputs/рисунки/схема_работы_агентной_бд.png (+ pdf)
"""

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyArrowPatch, FancyBboxPatch

ВЫХОД = Path(__file__).resolve().parents[1] / "outputs" / "рисунки"

ЦВЕТ = {
    "внешнее": ("#e8e8e8", "#8c8c8c"),   # источники вне базы
    "агент": ("#d6e6f7", "#2f6fa8"),     # что делает агент сам
    "база": ("#dff0dc", "#3f8a45"),      # таблицы базы
    "человек": ("#fde3d0", "#c2661f"),   # что подтверждает человек
    "журнал": ("#e8e0f3", "#6a4c9c"),    # сквозная запись
    "выход": ("#fdf3cf", "#a8871f"),     # потребители
}


def блок(ax, x, y, w, h, текст, вид, размер=9.5, жирный=False):
    заливка, рамка = ЦВЕТ[вид]
    ax.add_patch(
        FancyBboxPatch(
            (x, y), w, h,
            boxstyle="round,pad=0.02,rounding_size=0.12",
            facecolor=заливка, edgecolor=рамка, linewidth=1.6, zorder=2,
        )
    )
    ax.text(
        x + w / 2, y + h / 2, текст,
        ha="center", va="center", fontsize=размер, zorder=3,
        fontweight="bold" if жирный else "normal", linespacing=1.35,
    )
    return (x, y, w, h)


def стрелка(ax, откуда, куда, текст=None, стиль="-", цвет="#444444", сдвиг=0.0):
    ax.add_patch(
        FancyArrowPatch(
            откуда, куда,
            arrowstyle="-|>", mutation_scale=14, linewidth=1.5,
            color=цвет, linestyle=стиль, zorder=1,
            connectionstyle=f"arc3,rad={сдвиг}",
        )
    )
    if текст:
        сx = (откуда[0] + куда[0]) / 2
        сy = (откуда[1] + куда[1]) / 2 + 0.16
        ax.text(сx, сy, текст, ha="center", va="bottom", fontsize=8,
                color=цвет, zorder=3,
                bbox=dict(boxstyle="round,pad=0.15", fc="white", ec="none", alpha=0.85))


def main() -> None:
    ВЫХОД.mkdir(parents=True, exist_ok=True)
    fig, ax = plt.subplots(figsize=(16.5, 10.5))
    ax.set_xlim(0, 16.5)
    ax.set_ylim(0, 10.5)
    ax.axis("off")

    ax.text(0.25, 10.1, "Как работает агентная база данных",
            fontsize=19, fontweight="bold", va="center")
    ax.text(0.25, 9.7,
            "Узлы 3-4 технологической схемы: сбор сырых данных и паспортизация. "
            "Синее делает агент сам, оранжевое подтверждает человек.",
            fontsize=10.5, color="#555555", va="center")

    # ------------------------------------------------ ряд 1: приём данных
    и1 = блок(ax, 0.25, 7.75, 2.5, 1.25,
              "Открытые данные\nASTER, Sentinel,\nLandsat, рельеф", "внешнее")
    и2 = блок(ax, 0.25, 6.35, 2.5, 1.15,
              "Материалы\nорганизации\nГИС Интегро", "внешнее")
    и3 = блок(ax, 0.25, 5.05, 2.5, 1.05,
              "Публикации\nпо методам", "внешнее")

    сборщик = блок(ax, 3.5, 6.6, 2.7, 1.6,
                   "АГЕНТ-СБОРЩИК\n\nскачивает, считает хеш,\nопределяет контур съёмки",
                   "агент", жирный=False)
    приём = блок(ax, 7.0, 6.9, 2.2, 1.0, "staging\nприёмник", "база")
    слой = блок(ax, 10.0, 6.6, 3.0, 1.6,
                "data.source_layer\n+ meta.layer_passport\n\nисточник, лицензия,\nконтур, хеш, «выселен»",
                "база")

    for и in (и1, и2, и3):
        стрелка(ax, (и[0] + и[2], и[1] + и[3] / 2), (сборщик[0], 7.4))
    стрелка(ax, (сборщик[0] + сборщик[2], 7.4), (приём[0], 7.4))
    стрелка(ax, (приём[0] + приём[2], 7.4), (слой[0], 7.4), "паспортизация")

    # ------------------------------------------------ ряд 2: признаки
    пересчёт = блок(ax, 3.5, 4.3, 2.7, 1.4,
                    "ПЕРЕСЧЁТ В ЯЧЕЙКИ\n\nобщая сетка 500 м,\nодна система координат",
                    "агент")
    признаки = блок(ax, 7.0, 4.15, 2.2, 1.7,
                    "data.feature\ndata.feature_value\n\nкод + версия,\n11.8 млн значений", "база")
    паспорт = блок(ax, 10.0, 4.15, 3.0, 1.7,
                   "meta.feature_passport\nчерновик\n\nпокрытие, циркулярность,\n"
                   "переносимость,\nгеологический смысл", "база")

    стрелка(ax, (11.5, слой[1]), (11.5, паспорт[1] + паспорт[3]), сдвиг=0.0)
    стрелка(ax, (сборщик[0] + 1.35, сборщик[1]), (пересчёт[0] + 1.35, пересчёт[1] + пересчёт[3]))
    стрелка(ax, (пересчёт[0] + пересчёт[2], 5.0), (признаки[0], 5.0))
    стрелка(ax, (признаки[0] + признаки[2], 5.0), (паспорт[0], 5.0), "агент-паспортизатор")

    # ------------------------------------------------ база знаний
    знания = блок(ax, 13.6, 4.15, 2.6, 1.7,
                  "БАЗА ЗНАНИЙ\nkb + bridge\n\nпонятие ↔ признак\nкак гипотеза\nсо ссылкой", "агент")
    стрелка(ax, (паспорт[0] + паспорт[2], 5.3), (знания[0], 5.3))
    стрелка(ax, (знания[0], 4.7), (паспорт[0] + паспорт[2], 4.7), цвет="#2f6fa8")
    ax.text(13.45, 6.0, "обоснование\nиз литературы", fontsize=8, color="#2f6fa8",
            ha="center", va="bottom")

    # ------------------------------------------------ ряд 3: человек
    очередь = блок(ax, 10.0, 2.15, 3.0, 1.4,
                   "ОЧЕРЕДЬ ПОДТВЕРЖДЕНИЙ\n\n240 черновиков ждут\nрешения человека", "человек")
    человек = блок(ax, 13.6, 2.15, 2.6, 1.4,
                   "ЧЕЛОВЕК\n\nудаление\nлицензия\nгеологический смысл", "человек", жирный=True)
    стрелка(ax, (11.5, паспорт[1]), (11.5, очередь[1] + очередь[3]))
    стрелка(ax, (очередь[0] + очередь[2], 2.85), (человек[0], 2.85))
    стрелка(ax, (человек[0], 2.35), (очередь[0] + очередь[2], 2.35), цвет="#c2661f")
    ax.text(13.3, 3.62, "статус «подтверждён»\nставит только человек:\nагенту запрещено триггером",
            fontsize=8, color="#c2661f", ha="center", va="bottom")

    # ------------------------------------------------ выход
    снимок = блок(ax, 6.3, 2.15, 2.9, 1.4,
                  "СНИМОК ДЛЯ ОПЫТА\n\nнеизменяемый parquet\n+ манифест", "выход")
    модели = блок(ax, 3.1, 2.6, 2.6, 0.95, "Обучение моделей,\nпрогнозные карты", "выход")
    qgis = блок(ax, 3.1, 1.45, 2.6, 0.9, "QGIS, просмотр\nи проверка", "выход")
    стрелка(ax, (очередь[0], 2.85), (снимок[0] + снимок[2], 2.85), "только\nподтверждённое")
    стрелка(ax, (снимок[0], 3.0), (модели[0] + модели[2], 3.05))
    стрелка(ax, (снимок[0], 2.5), (qgis[0] + qgis[2], 2.0))

    # ------------------------------------------------ сквозные контуры
    журнал = блок(ax, 3.1, 0.35, 10.0, 0.75,
                  "runs.run  +  meta.operation  →  meta.derivation      "
                  "журнал прогонов и граф происхождения: версия кода, хеши входов, "
                  "модель агента — пишутся на каждой стрелке", "журнал", размер=9)
    for x in (4.8, 7.0, 9.2, 11.5):
        стрелка(ax, (x, 2.1), (x, журнал[1] + журнал[3]), цвет="#6a4c9c", стиль=":")

    пробелы = блок(ax, 0.25, 1.45, 2.6, 2.05,
                   "meta.gap\nРЕЕСТР ПРОБЕЛОВ\n\nаэрогамма K/eU/eTh,\nгеохимия, pathfinder,\n"
                   "ASTER вне контура\n\nчего нет — тоже\nфакт базы", "база", размер=9)
    стрелка(ax, (модели[0], 3.2), (пробелы[0] + пробелы[2], 3.2), цвет="#3f8a45", стиль="--")
    ax.text(1.55, 3.62, "данных недостаточно →\nзапрос или отказ", fontsize=8.5,
            color="#3f8a45", ha="center", va="bottom")

    # ------------------------------------------------ легенда
    подписи = [
        ("внешнее", "вне базы"),
        ("агент", "делает агент"),
        ("база", "таблицы базы"),
        ("человек", "решает человек"),
        ("выход", "потребители"),
        ("журнал", "сквозная запись"),
    ]
    for i, (вид, текст) in enumerate(подписи):
        x = 0.3 + i * 1.55
        заливка, рамка = ЦВЕТ[вид]
        ax.add_patch(FancyBboxPatch((x, 0.05), 0.3, 0.22,
                                    boxstyle="round,pad=0.01,rounding_size=0.05",
                                    facecolor=заливка, edgecolor=рамка, linewidth=1.2))
        ax.text(x + 0.4, 0.16, текст, fontsize=8.5, va="center", color="#333333")

    ax.text(16.25, 0.16,
            "PostgreSQL 18 + PostGIS 3.6, порт 5433 · gis_agent — запись без удаления",
            fontsize=8.5, color="#777777", ha="right", va="center")

    fig.tight_layout()
    for расширение in ("png", "pdf"):
        путь = ВЫХОД / f"схема_работы_агентной_бд.{расширение}"
        fig.savefig(путь, dpi=200, bbox_inches="tight", facecolor="white")
        print(f"записано: {путь}")
    plt.close(fig)


if __name__ == "__main__":
    main()
