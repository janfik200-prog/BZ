GENERAL_RULE = (
    "Вопрос общий, без названного места. Если во фрагментах только сведения по отдельным "
    "площадям и месторождениям, давай их как примеры с указанием места, а не как определение "
    "или общее правило."
)
_SUPERLATIVE = re.compile(r"\b(?:основн|главн|лучш|наиболее|самы[йеха])", re.IGNORECASE)
# Имя собственное не в начале фразы: «баженовская» пишут строчной, «Западной Сибири» — нет.
_PROPER = re.compile(r"(?<![.!?]\s)(?<!^)\b[А-ЯЁA-Z][а-яёa-z-]{2,}")


def situational_rules(question: str, sources: list[dict[str, Any]]) -> list[str]:
    """Узкие правила короткого промта — только когда нужны по вопросу и фрагментам."""
    rules = []
    if "формул" in question.lower() or any("$$" in str(s.get("text") or "") for s in sources):
        rules.append(FORMULA_RULE)
    if _SUPERLATIVE.search(question):
        rules.append(SUPERLATIVE_RULE)
    if not _PROPER.search(question.strip()):
        rules.append(GENERAL_RULE)
    return rules


# Вопрос, который что-то подаёт как известное («Почему X…», «Раз X…», «Поскольку…»). Без
