"""Извлечение сущностей из текста статьи: объекты, полезные ископаемые, методы.

Почему правилами, а не моделью. Русские геологические названия устроены
на редкость единообразно: имя собственное в форме прилагательного плюс опорное
слово — «Тырныаузский рудный узел», «Крайчиковское рудопроявление»,
«Далдыно-Алакитский район». Опорных слов конечное число, и они лежат ниже
списком. По такому шаблону названия достаются почти без ошибок и, главное,
одинаково от прогона к прогону — в отличие от модели, которая на одном и том же
тексте дважды ответит немного по-разному.

Чего правила не умеют: назвать объект, у которого имя не прилагательное
(«кимберлитовое поле Далдын»), и понять, что два разных написания — одно и то же.
Это работа для модели, и она ложится сверху: ключи у сущностей общие.

Склонения снимаются по окончанию, а род восстанавливается по опорному слову —
оно же и задаёт, каким должно быть прилагательное в именительном падеже:
«рудного узла» → мужской → «Тырныаузский рудный узел».
"""

from __future__ import annotations

import re
from dataclasses import dataclass

OBJECT = "объект"
COMMODITY = "ископаемое"
METHOD = "метод"

# Опорные слова: канонический вид, шаблон всех форм, род.
# Род нужен, чтобы вернуть прилагательному именительный падеж.
HEADS: list[tuple[str, str, str]] = [
    ("рудный узел",      r"рудн\w*\s+уз(?:ел|л\w+)", "м"),
    ("рудное поле",      r"рудн\w*\s+пол(?:е|я|ю|ем|ей|ях|ями)", "с"),
    ("рудный район",     r"рудн\w*\s+район\w*", "м"),
    ("рудопроявление",   r"рудопроявлени\w*", "с"),
    ("месторождение",    r"месторождени\w*", "с"),
    ("кимберлитовая трубка", r"кимберлитов\w*\s+трубк\w*", "ж"),
    ("трубка",           r"трубк\w*", "ж"),
    ("площадь",          r"площад(?:ь|и|ью|ям|ей|ями)", "ж"),
    ("поднятие",         r"подняти\w*", "с"),
    ("кряж",             r"кряж\w*", "м"),
    ("щит",              r"щит\w*", "м"),
    ("массив",           r"массив\w*", "м"),
    ("комплекс",         r"комплекс\w*", "м"),
    ("свита",            r"свит(?:а|ы|е|у|ой|ам|ах)", "ж"),
    ("разлом",           r"разлом\w*", "м"),
    ("зона",             r"зон(?:а|ы|е|у|ой|ам|ах|ами)", "ж"),
    ("провинция",        r"провинци\w*", "ж"),
    ("кратон",           r"кратон\w*", "м"),
    ("платформа",        r"платформ\w*", "ж"),
    ("грабен",           r"грабен\w*", "м"),
    ("антиклинорий",     r"антиклинори\w*", "м"),
    ("синклинорий",      r"синклинори\w*", "м"),
    ("район",            r"район\w*", "м"),
]

# Имя собственное: слово с заглавной, возможно через дефис («Далдыно-Алакитский»,
# «Усть-Балык-Мамонтовского»).
_NAME = r"[А-ЯЁ][а-яё]+(?:[-–][А-ЯЁа-яё][а-яё]+)*"

# Окончания прилагательных, которые снимаем, чтобы получить основу имени.
_ADJ_TAIL = re.compile(
    r"(ского|скому|ским|ском|ской|скую|ская|ское|ские|ских|скими|ский"
    r"|ого|ому|ым|ом|ая|ой|ую|ое|ые|ых|ыми|ый"
    r"|его|ему|им|ем|яя|ей|юю|ее|ие|их|ими|ий)$"
)
_ADJ_NOMINATIVE = {"м": "ский", "ж": "ская", "с": "ское"}

# Между именем и опорным словом часто стоит ещё одно прилагательное:
# «Анабарского кристаллического массива», «Северо-Енисейского рудного района».
_MIDDLE = r"(?:\s+[а-яё]+(?:[-–][а-яё]+)*)?"

# Регистр важен: имя собственное с заглавной, опорное слово — любое.
# Флаг IGNORECASE на весь шаблон обнулял бы это различие, и «пересечения
# разломов» становилось бы «объектом» — проверено на живом тексте.
OBJECT_PATTERNS = [
    (canon, gender,
     re.compile(rf"\b(?P<name>{_NAME}){_MIDDLE}\s+(?P<head>(?i:{form}))", re.UNICODE))
    for canon, form, gender in HEADS
]

# Полезные ископаемые: разные написания сводим к одному слову.
COMMODITIES: dict[str, str] = {
    "золото": r"золот\w*|золоторудн\w*|\bgold\b|\bAu\b",
    # Формы «медь/меди/медью» перечислены явно: шаблон вроде мед\w* цеплял бы
    # «медленно» и «между».
    "медь": r"медн\w*|\bмед(?:ь|и|ью|ям|ями|ей)\b|\bcopper\b|\bCu\b",
    "алмазы": r"алмаз\w*|алмазоносн\w*|\bdiamond\w*",
    "уран": r"уран\w*|\buranium\b|\bU\b",
    "никель": r"никел\w*|\bnickel\b|\bNi\b",
    "платиноиды": r"платин\w*|платиноид\w*|\bplatinum\b|\bPGE\b",
    "молибден": r"молибден\w*|\bmolybdenum\b|\bMo\b",
    "вольфрам": r"вольфрам\w*|\btungsten\b|\bW\b",
    "олово": r"\bолов(?:о|а|у|ом)\b|оловорудн\w*|\btin\b|\bSn\b",
    "редкие земли": r"редкоземельн\w*|редких земель|\bREE\b|rare earth",
    "железо": r"железорудн\w*|\bжелез(?:о|а|у|ом)\b|\biron ore\b",
    "полиметаллы": r"полиметалл\w*|\bpolymetallic\b",
}

# Методы и данные: то, чем в статье работали.
METHODS: dict[str, str] = {
    "ASTER": r"\bASTER\b",
    "Landsat": r"\bLandsat[- ]?\d*\b",
    "Sentinel": r"\bSentinel[- ]?\d*\b",
    "дистанционное зондирование": r"дистанционн\w*\s+зондировани\w*|remote sensing",
    "линеаментный анализ": r"линеаментн\w*\s+анализ\w*|плотност\w*\s+линеамент\w*|lineament",
    "метод главных компонент": r"главн\w*\s+компонент\w*|principal component",
    "геохимическая съёмка": r"геохимическ\w*\s+съёмк\w*|геохимическ\w*\s+съемк\w*|вторичн\w*\s+ореол\w*",
    "машинное обучение": r"машинн\w*\s+обучени\w*|machine learning|нейронн\w*\s+сет\w*|random forest",
    "весов доказательств": r"весов\s+доказательств|weights[- ]of[- ]evidence",
    "ГИС": r"\bГИС\b|\bGIS\b",
    "магниторазведка": r"магниторазведк\w*|магнитн\w*\s+пол\w*|magnetic surve\w*",
    "гравиразведка": r"гравиразведк\w*|гравитационн\w*\s+аномали\w*|gravity anomal\w*",
    "кокригинг": r"кокригинг\w*|cokriging",
}

COMMODITY_PATTERNS = [(name, re.compile(p, re.IGNORECASE | re.UNICODE)) for name, p in COMMODITIES.items()]
METHOD_PATTERNS = [(name, re.compile(p, re.IGNORECASE | re.UNICODE)) for name, p in METHODS.items()]

# Прилагательные, которые по форме неотличимы от имени собственного, но именем
# не являются. Сравниваются по основе, поэтому все падежи покрыты разом.
NOT_NAME_STEMS = {
    "рудн", "кимберлитов", "данн", "настоящ", "рассматриваем", "исследуем",
    "указанн", "эт", "так", "втор", "перв", "нов", "северн", "южн", "восточн",
    "западн", "центральн", "верхн", "нижн", "крупн", "мелк", "основн", "главн",
    "интенсивн", "разнонаправленн", "максимальн", "минимальн", "локальн",
    "региональн", "единичн", "отдельн", "различн", "перспективн", "изученн",
    "золоторудн", "медн", "алмазоносн", "продуктивн", "древн", "молод",
}


@dataclass(frozen=True)
class Entity:
    key: str     # нормализованный ключ — по нему сущности схлопываются
    name: str    # как показывать человеку
    kind: str    # объект | ископаемое | метод


def _nominative(name: str, gender: str) -> str:
    """Вернуть имя-прилагательное в именительный падеж по роду опорного слова."""
    parts = name.replace("–", "-").split("-")
    tail = _ADJ_TAIL.search(parts[-1].lower())
    if not tail:
        return name  # не прилагательное — оставляем как есть
    stem = parts[-1][: -len(tail.group(0))]
    parts[-1] = stem + _ADJ_NOMINATIVE[gender]
    return "-".join(p[:1].upper() + p[1:] for p in parts)


def _key(name: str, kind: str) -> str:
    """Ключ без падежей и регистра: «Тырныаузского» и «Тырныаузский» — одно и то же."""
    base = _ADJ_TAIL.sub("", name.lower().replace("ё", "е").replace("–", "-"))
    return f"{kind}:{re.sub(r'[^a-zа-я0-9-]+', '', base)}"


def _stem(word: str) -> str:
    return _ADJ_TAIL.sub("", word.lower().replace("ё", "е"))


def _is_name(raw: str) -> bool:
    """Годится ли слово в имя собственное.

    Требуем окончание прилагательного: почти все здешние названия —
    «Тырныаузский», «Крайчиковское», «Далдыно-Алакитский». Существительное
    с заглавной в начале предложения («Металлогения массива изучена слабо»)
    так отсекается. Платим за это тем, что «трубка Удачная» и другие названия
    с обратным порядком слов не ловятся: их дополнит модель.
    """
    if len(raw) < 5:
        return False
    last = raw.replace("–", "-").split("-")[-1]
    if not _ADJ_TAIL.search(last.lower()):
        return False
    return not any(_stem(part) in NOT_NAME_STEMS for part in raw.replace("–", "-").split("-"))


def extract(text: str) -> list[Entity]:
    """Сущности из одного куска текста. Повторы внутри куска схлопываются."""
    found: dict[str, Entity] = {}
    claimed: list[tuple[int, int]] = []   # что уже разобрано более точным шаблоном

    def overlaps(span):
        return any(span[0] < end and start < span[1] for start, end in claimed)

    # Порядок важен: «кимберлитовая трубка» разбирается раньше «трубки»,
    # «рудный район» — раньше «района», иначе одно место попадёт в граф дважды.
    for canon, gender, pattern in OBJECT_PATTERNS:
        for match in pattern.finditer(text):
            if overlaps(match.span()):
                continue
            raw = match.group("name")
            if not _is_name(raw):
                continue
            claimed.append(match.span())
            title = f"{_nominative(raw, gender)} {canon}"
            key = _key(raw, OBJECT) + ":" + canon.replace(" ", "-")
            found.setdefault(key, Entity(key, title, OBJECT))

    for name, pattern in COMMODITY_PATTERNS:
        if pattern.search(text):
            key = _key(name, COMMODITY)
            found.setdefault(key, Entity(key, name, COMMODITY))

    for name, pattern in METHOD_PATTERNS:
        if pattern.search(text):
            key = _key(name, METHOD)
            found.setdefault(key, Entity(key, name, METHOD))

    return list(found.values())
