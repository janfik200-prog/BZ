def para(text: str = "", style: str = "Normal", align=None, bold=False, size=None, indent=None, keep=False):
    p = doc.add_paragraph(style=style)
    if align is not None:
        p.alignment = align
    if indent is False:
        p.paragraph_format.first_line_indent = Cm(0)
    if keep:
        p.paragraph_format.keep_with_next = True
    r = p.add_run(text)
    r.bold = bold or None
    if size:
        r.font.size = Pt(size)
    return p


