def _facts() -> dict:
    """120 случайных связей графа, размеченных автором (research/v15/Разметка_v15_автор.xlsx,
    лист «Факты»; выборка — research/v15/results/search_key.json, зерно 20261030)."""
    from openpyxl import load_workbook

    ws = load_workbook(str(V15.parent / "Разметка_v15_автор.xlsx"), data_only=True)["Факты"]
    marks = [int(ws.cell(r, 7).value) for r in range(2, ws.max_row + 1)
             if str(ws.cell(r, 7).value).strip() in ("0", "1")]
    k, n_ = sum(marks), len(marks)
    z = 1.96
    c = (k / n_ + z * z / (2 * n_)) / (1 + z * z / n_)
    h = z * ((k / n_) * (1 - k / n_) / n_ + z * z / (4 * n_ * n_)) ** 0.5 / (1 + z * z / n_)
    # Причины 16 ошибок — по комментариям автора к неверным связям (разбор 30.10.2026).
    return {"n": n_, "correct": k, "p": k / n_, "ci": (c - h, c + h),
            "errors": {"потеряна оговорка о предположительности": 7, "неверный тип связи": 6,
                       "связь не геологического содержания": 2, "обратное направление": 1}}


