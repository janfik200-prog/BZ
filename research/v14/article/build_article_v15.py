def _qa() -> dict:
    """Вопросы по статьям базы (research/v15/article_qa.py), оставленные после проверки:
    доли «статья среди пяти», «статья первой», «фрагмент среди пяти» и попарные разности."""
    import random
    import statistics

    from openpyxl import load_workbook

    runs = json.loads((V15 / "article_qa_runs.json").read_text("utf-8"))
    ws = load_workbook(str(V15.parent / "Разметка_вопросы_по_статьям_проверено.xlsx"), data_only=True)["Вопросы"]
    sel = [x for i, x in enumerate(runs, 1) if str(ws.cell(i + 1, 6).value).strip() == "1"]

    def top5(x, m):
        return int(x["doc_id"] in x["docs"][m])

    def first(x, m):
        return int(bool(x["docs"][m]) and x["docs"][m][0] == x["doc_id"])

    def frag(x, m):
        return int(x["chunk_id"] in x["runs"][m])

    def paired(f, a, b, xs):
        d = [f(x, a) - f(x, b) for x in xs]
        rng = random.Random(1)
        boot = sorted(statistics.mean(rng.choice(d) for _ in d) for _ in range(10000))
        return statistics.mean(d), boot[250], boot[9750]

    out = {"generated": len(runs), "used": len(sel),
           "places": sum(bool(x["info"]["names"]) for x in sel),
           "seconds": statistics.median(x["info"]["seconds_extra"] for x in sel)}
    for part, xs in (("all", sel), ("place", [x for x in sel if x["info"]["names"]]),
                     ("noplace", [x for x in sel if not x["info"]["names"]])):
        out[part] = {m: {"top5": statistics.mean(top5(x, m) for x in xs),
                         "first": statistics.mean(first(x, m) for x in xs),
                         "frag": statistics.mean(frag(x, m) for x in xs)} for m in ("vector", "hybrid", "system")}
        out[part]["n"] = len(xs)
    out["d_top5_hybrid"] = paired(top5, "system", "hybrid", sel)
    out["d_first_hybrid"] = paired(first, "system", "hybrid", sel)
    out["d_first_vector"] = paired(first, "system", "vector", sel)
    return out


