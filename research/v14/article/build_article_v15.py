def n(x) -> str:
    """Число с пробелом в разрядах: 13739 → «13 739»."""
    return f"{int(x):,}".replace(",", " ")


def dec(x, d: int = 2) -> str:
    return PENDING if x is None else f"{x:.{d}f}".replace(".", ",")


def pc(x) -> str:
    """Доля как целый процент: 0,945 → «94»."""
    return str(round(100 * x))


def pct(a, b) -> str:
    return f"{100 * a / b:.1f}".replace(".", ",")


def table(caption: str, header: list[str], rows: list[list[str]], widths: list[float], size: float = 11):
    para(caption, "Table caption", keep=True)
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    borders = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{side}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        borders.append(e)
    t._tbl.tblPr.append(borders)
    for i, row in enumerate([header, *rows]):
        for j, v in enumerate(row):
            c = t.rows[i].cells[j]
            c.width = Cm(widths[j])
            pp = c.paragraphs[0]
            pp.paragraph_format.first_line_indent = Cm(0)
            pp.alignment = L.LEFT if j == 0 else L.CENTER
            r = pp.add_run(str(v))
            r.font.size = Pt(size)
            r.bold = i == 0 or None
    para("", indent=False)


