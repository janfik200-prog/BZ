def shade(cell, color: str) -> None:
    tcpr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color)
    tcpr.append(shd)


def borders(table) -> None:
    b = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:color"), "808080")
        b.append(e)
    table._tbl.tblPr.append(b)


def fixed_widths(table, widths_cm: list[float]) -> None:
    table.autofit = False
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    table._tbl.tblPr.append(layout)
    for j, w in enumerate(widths_cm):
        table._tbl.tblGrid.findall(qn("w:gridCol"))[j].set(qn("w:w"), str(int(w * 567)))
    for row in table.rows:
        for j, w in enumerate(widths_cm):
            row.cells[j].width = Cm(w)


def cell_text(cell, text: str, bold: bool = False, size: float = 10, color: str | None = None, center: bool = False) -> None:
    cell.text = ""
    p = cell.paragraphs[0]
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    r.bold = bold
    r.font.size = Pt(size)
    if color:
        r.font.color.rgb = RGBColor.from_string(color)


