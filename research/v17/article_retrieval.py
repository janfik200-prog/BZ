def d(x: float) -> str:
    return f"{x:.2f}".replace(".", ",").replace("-", "−")


def ci(v: list[float]) -> str:
    """«0,07 (интервал 0,04–0,12)»; при отрицательной границе — «от … до …»."""
    span = f"от {d(v[1])} до {d(v[2])}" if v[1] < 0 else f"{d(v[1])}–{d(v[2])}"
    return f"{d(v[0])} (интервал {span})"


