def set_text(par, text: str) -> None:
    runs = par.runs
    runs[0].text = text
    for r in runs[1:]:
        r._r.getparent().remove(r._r)


def set_cell(cell, text: str) -> None:
    ps = cell.paragraphs
    set_text(ps[0], text)
    for p in ps[1:]:
        p._p.getparent().remove(p._p)


def main(src: str, out: str) -> None:
    doc = Document(src)
    T = texts()
    table4 = T.pop("_table4")
    for start, text in T.items():
        hits = [p for p in doc.paragraphs if p.text.startswith(start)]
        assert len(hits) == 1, (start, len(hits))
        set_text(hits[0], text)

    # Табл. 4 — после абзаца обсуждения, оформление — копия табл. 3 без последнего столбца.
    anchor = next(p for p in doc.paragraphs if p.text.startswith("Полученные результаты демонстрируют"))
    cap3 = next(p for p in doc.paragraphs if p.text.startswith("Таблица 3."))
    cap = copy.deepcopy(cap3._p)
    tbl = copy.deepcopy(doc.tables[2]._tbl)
    anchor._p.addnext(cap)
    cap.addnext(tbl)
    from docx.table import Table
    from docx.text.paragraph import Paragraph

    set_text(Paragraph(cap, anchor._parent), "Таблица 4. Проверки по этапам построения базы и поиска")
    t = Table(tbl, anchor._parent)
    ns = tbl.nsmap["w"]
    grid = tbl.find(f"{{{ns}}}tblGrid")
    cols = grid.findall(f"{{{ns}}}gridCol")
    grid.remove(cols[-1])
    for row in t.rows:
        tcs = row._tr.findall(f"{{{ns}}}tc")
        row._tr.remove(tcs[-1])
    while len(t.rows) > len(table4):
        t._tbl.remove(t.rows[-1]._tr)
    total = sum(int(c.get(f"{{{ns}}}w")) for c in cols)
    widths = [0.20, 0.24, 0.38, 0.18]
    for c, w in zip(grid.findall(f"{{{ns}}}gridCol"), widths):
        c.set(f"{{{ns}}}w", str(int(total * w)))
    for row, vals in zip(t.rows, table4):
        for cell, v, w in zip(row.cells, vals, widths):
            set_cell(cell, v)
            tcw = cell._tc.tcPr.find(f"{{{ns}}}tcW") if cell._tc.tcPr is not None else None
            if tcw is not None:
                tcw.set(f"{{{ns}}}w", str(int(total * w)))
                tcw.set(f"{{{ns}}}type", "dxa")
    doc.save(out)
    chars = sum(len(p.text) for p in doc.paragraphs) + sum(len(c.text) for tb in doc.tables for r in tb.rows
                                                          for c in r.cells)
    print(out, "знаков с пробелами (абзацы + таблицы):", chars)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
