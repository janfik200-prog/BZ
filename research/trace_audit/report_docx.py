# --------------------------------------------------------------------------- числа
def n(x: int) -> str:
    if isinstance(x, X):
        return MARK
    return f"{x:,}".replace(",", " ")


def p(x: float | None) -> str:
    if isinstance(x, X):
        return MARK
    return "—" if x is None else f"{x:.1f}".replace(".", ",")


def frac(d: dict) -> str:
    if isinstance(d, X):
        return f"{MARK} из {MARK} ({MARK} %)"
    return f"{n(d['k'])} из {n(d['n'])} ({p(d['pct'])} %)"


