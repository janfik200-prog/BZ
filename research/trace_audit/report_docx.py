def render_pages(path: str) -> tuple[dict[str, int], int]:
    """Номера страниц заголовков — по PDF (LibreOffice)."""
    tmp = Path(tempfile.mkdtemp())
    pdf = tmp / "out.pdf"
    src = str(Path(path).resolve())
    ps = (f"$w = New-Object -ComObject Word.Application; $w.Visible = $false; "
          f"$d = $w.Documents.Open('{src}', $false, $true); $d.ExportAsFixedFormat('{pdf}', 17); "
          f"$d.Close($false); $w.Quit()")
    subprocess.run(["powershell", "-NoProfile", "-Command", ps], check=True, capture_output=True)
    import pymupdf

    doc = pymupdf.open(pdf)
    pages: dict[str, int] = {}
    heads = ["ТЕРМИНЫ И ОПРЕДЕЛЕНИЯ", "ПЕРЕЧЕНЬ СОКРАЩЕНИЙ И ОБОЗНАЧЕНИЙ", "ВВЕДЕНИЕ", H0, *H_ALL,
             "ЗАКЛЮЧЕНИЕ", "СПИСОК ИСПОЛЬЗОВАННЫХ ИСТОЧНИКОВ"]
    for i, page in enumerate(doc, 1):
        if i <= 2:  # реферат и содержание
            continue
        lines = [" ".join(ln.split()) for ln in page.get_text().splitlines()]
        text = " ".join(lines)
        for h in heads:
            if h not in pages and (h in lines or (len(h) > 40 and h in text)):
                pages[h] = i
    return pages, len(doc)


