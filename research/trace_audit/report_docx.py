class X:
    """Числа ещё нет: любое обращение — снова X, в тексте — «[ПК2]»."""

    def __getitem__(self, k):
        return X()

    def get(self, *a):
        return X()

    def items(self):
        return []

    def __add__(self, o):
        return X()

    __radd__ = __sub__ = __rsub__ = __add__

    def __bool__(self):
        return True

    def __str__(self):
        return MARK

    def __format__(self, spec):
        return MARK
