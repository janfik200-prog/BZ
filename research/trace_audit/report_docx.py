def example(c) -> dict:
    """Связь графа для примера цепочки: подтверждена 4 из 4, территория из цитаты, по-русски."""
    rows = list(csv.DictReader((RES / "facts.csv").open(encoding="utf-8")))
    best = None
    for r in rows:
        if (r["в графе"] == "1" and r["вердикт"] == "подтверждена" and r["территория откуда"] == "из цитаты"
                and re.search("[а-яё]", r["quote"], re.I) and 90 <= len(r["quote"]) <= 260
                and len(r["src"]) <= 40 and len(r["dst"]) <= 50 and r["страницы"]):
            best = r
            break
    if best is None:
        return {}
    cid = c.execute("SELECT f.chunk_id FROM facts f WHERE f.id = %s", (int(best["id"]),)).fetchone()[0]
    heads, year, title = c.execute(
        "SELECT c.headings, d.year, d.title FROM chunks c JOIN documents d ON d.doc_id = c.doc_id "
        "WHERE c.id = %s", (cid,)).fetchone()
    return {**best, "headings": heads or [], "year": year, "title": title}


# --------------------------------------------------------------------------- оформление
def runs_of(par, text: str, rpr, tab: bool = False) -> None:
    """Текст абзаца прогонами; «[ПК2…]» — жёлтой заливкой."""
    parts = [x for x in re.split(r"(\[ПК2[^\]]*\])", text) if x] or [""]
    for j, part in enumerate(parts):
        r = etree.SubElement(par, qn("w:r"))
        rp = copy.deepcopy(rpr) if rpr is not None else None
        if part.startswith("[ПК2"):
            if rp is None:
                rp = etree.Element(qn("w:rPr"))
            etree.SubElement(rp, qn("w:highlight")).set(qn("w:val"), "yellow")
        if rp is not None:
            r.append(rp)
        if tab and j == 0:
            etree.SubElement(r, qn("w:tab"))
        t = etree.SubElement(r, qn("w:t"))
        t.text = part
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")


class Doc:
    def __init__(self, src: str) -> None:
        self.d = docx.Document(src)
        body = self.d.element.body
        items = list(body.iterchildren())
        by_style: dict[str, etree._Element] = {}
        for el in items:
            if el.tag == qn("w:p"):
                st = el.find(qn("w:pPr"))
                name = st.find(qn("w:pStyle")).get(qn("w:val")) if st is not None and st.find(qn("w:pStyle")) is not None else "Normal"
                text = "".join(t.text or "" for t in el.iter(qn("w:t")))
                if text.strip() and name not in by_style and not el.findall(".//" + qn("w:drawing")):
                    by_style[name] = copy.deepcopy(el)
        # обычный абзац — длинный абзац текста, а не строка реферата «Отчёт 16 с.»
        for el in items:
            text = "".join(t.text or "" for t in el.iter(qn("w:t")))
            if el.tag == qn("w:p") and text.startswith("Для прогноза оруденения"):
                by_style["Normal"] = copy.deepcopy(el)
            if el.tag == qn("w:p") and text == "СОДЕРЖАНИЕ":  # заголовок с новой страницы
                by_style["ReportFront"] = copy.deepcopy(el)
        self.tpl = by_style
        self.cell = None
        for el in items:
            if el.tag == qn("w:tbl"):
                self.tbl = copy.deepcopy(el)
                break
        self.sect = items[-1]
        for el in items[:-1]:
            body.remove(el)
        self.body = body

    def _para(self, style: str, text: str) -> etree._Element:
        el = copy.deepcopy(self.tpl[style])
        runs = el.findall(qn("w:r"))
        rpr = runs[0].find(qn("w:rPr")) if runs else None
        for child in list(el):
            if child.tag != qn("w:pPr"):
                el.remove(child)
        for i, part in enumerate(text.split("\t")):
            runs_of(el, part, rpr, tab=bool(i))
        return el

    def add(self, style: str, text: str) -> None:
        self.sect.addprevious(self._para(style, text))

    def front(self, t: str) -> None:
        el = self._para("ReportFront", t)
        if t == "РЕФЕРАТ":  # первая страница — без разрыва перед ней
            for br in el.iter(qn("w:pageBreakBefore")):
                br.getparent().remove(br)
        self.sect.addprevious(el)

    def text(self, t: str) -> None:
        self.add("Normal", t)

    def h(self, level: int, t: str) -> None:
        self.add({0: "Title", 1: "Heading1", 2: "Heading2", 3: "Heading3"}[level], t)

    def table(self, caption: str, widths: list[int], rows: list[list[str]]) -> None:
        self.add("ReportCaption", caption)
        tbl = copy.deepcopy(self.tbl)
        grid = tbl.find(qn("w:tblGrid"))
        for g in list(grid):
            grid.remove(g)
        for w in widths:
            etree.SubElement(grid, qn("w:gridCol")).set(qn("w:w"), str(w))
        trs = tbl.findall(qn("w:tr"))
        head_tr, body_tr = trs[0], trs[1]
        for tr in trs:
            tbl.remove(tr)
        for ri, row in enumerate(rows):
            tr = copy.deepcopy(head_tr if ri == 0 else body_tr)
            tcs = tr.findall(qn("w:tc"))
            tc_tpl = tcs[-1] if ri == 0 else tcs[0]
            for tc in tcs:
                tr.remove(tc)
            for ci, val in enumerate(row):
                tc = copy.deepcopy(tc_tpl)
                tc.find(qn("w:tcPr")).find(qn("w:tcW")).set(qn("w:w"), str(widths[ci]))
                par = tc.find(qn("w:p"))
                jc = par.find(qn("w:pPr")).find(qn("w:jc"))
                if ri and jc is not None:
                    par.find(qn("w:pPr")).remove(jc)
                for r in par.findall(qn("w:r")):
                    par.remove(r)
                runs_of(par, val, None)
                tr.append(tc)
            tbl.append(tr)
        self.sect.addprevious(tbl)


