def nbsp(text: str) -> str:
    """Неразрывные пробелы, как в исходном отчёте: внутри чисел («2 059»), перед «%»,
    после «с.» и перед ссылкой [N] — чтобы перенос строки их не разрывал."""
    text = re.sub(r"(?<=\d) (?=\d{3}(?!\d))", "\xa0", text)
    text = re.sub(r" (?=%)", "\xa0", text)
    text = re.sub(r"(?<=\bс\.) (?=\d)", "\xa0", text)
    return re.sub(r" (?=\[\d)", "\xa0", text)


def set_text(par, text: str) -> None:
    """Текст абзаца заменяется целиком; оформление — первого прогона. Метки — жёлтым."""
    text = nbsp(text)
    runs = par._p.findall(qn("w:r"))
    rpr = runs[0].find(qn("w:rPr")) if runs else None
    rpr = copy.deepcopy(rpr) if rpr is not None else None
    for r in runs:
        par._p.remove(r)
    for part in (x for x in MARK.split(text) if x):
        r = etree.SubElement(par._p, qn("w:r"))
        rp = copy.deepcopy(rpr) if rpr is not None else None
        if MARK.fullmatch(part):
            if rp is None:
                rp = etree.Element(qn("w:rPr"))
            etree.SubElement(rp, qn("w:highlight")).set(qn("w:val"), "yellow")
        if rp is not None:
            r.append(rp)
        t = etree.SubElement(r, qn("w:t"))
        t.text = part
        t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")


def replace_figure(d) -> None:
    blips = d.element.body.findall(".//" + qn("a:blip"))
    assert len(blips) == 1, "в отчёте ожидался один рисунок"
    rid = blips[0].get(qn("r:embed"))
    d.part.related_parts[rid]._blob = FIG.read_bytes()
    w, h = Image.open(FIG).size
    inline = blips[0].getparent()
    while inline.tag not in (qn("wp:inline"), qn("wp:anchor")):
        inline = inline.getparent()
    ext = inline.find(qn("wp:extent"))
    cx = int(ext.get("cx"))
    cy = round(cx * h / w)
    ext.set("cy", str(cy))
    for e in inline.iter(qn("a:ext")):
        if e.get("cx") == str(cx):
            e.set("cy", str(cy))


def table_rows(table, rows: list[list[str]]) -> None:
    """Таблица заново по образцу её второй строки: заголовок — первая строка, оформление ячеек
    данных — второй; лишние строки убираются."""
    trs = [r._tr for r in table.rows]
    template = copy.deepcopy(trs[1])
    for tr in trs[1:]:
        tr.getparent().remove(tr)
    for cell, text in zip(table.rows[0].cells, rows[0]):
        set_text(cell.paragraphs[0], text)
    for values in rows[1:]:
        tr = copy.deepcopy(template)
        trs[0].getparent().append(tr)
        for cell, text in zip(table.rows[-1].cells, values):
            set_text(cell.paragraphs[0], text)
            for extra in cell.paragraphs[1:]:
                extra._p.getparent().remove(extra._p)


def main(src: str, dst: str) -> None:
    d = docx.Document(src)
    for p in d.paragraphs:
        text = p.text.replace("\xa0", " ")
        head = text.split("\t")[0].strip()
        if head in HEADINGS:
            if "\t" in text:  # строка содержания: текст до табуляции, номер страницы не трогать
                p._p.findall(".//" + qn("w:t"))[0].text = HEADINGS[head]
            else:
                set_text(p, HEADINGS[head])
    done = set()
    for p in d.paragraphs:
        for start, text in PARAS.items():
            if start not in done and p.text.replace("\xa0", " ").strip().startswith(start):
                if text is None:
                    p._p.getparent().remove(p._p)
                else:
                    set_text(p, text)
                done.add(start)
                break
    missed = [s for s in PARAS if s not in done]
    assert not missed, f"не найдены абзацы: {missed}"
    for start, text in INSERT_AFTER.items():
        p = next(p for p in d.paragraphs if p.text.startswith(start))
        new = copy.deepcopy(p._p)
        p._p.addnext(new)
        set_text(docx.text.paragraph.Paragraph(new, p._parent), text)
    table_rows(d.tables[1], TABLE2)
    # Таблица 4: подпись — по образцу подписи таблицы 3, таблица — по образцу таблицы 2.
    anchor = next(p for p in d.paragraphs if p.text.startswith(TABLE4_AFTER))
    caption_src = next(p for p in d.paragraphs if p.text.startswith("Таблица 3 –"))
    caption = copy.deepcopy(caption_src._p)
    anchor._p.addnext(caption)
    set_text(docx.text.paragraph.Paragraph(caption, anchor._parent), TABLE4_CAPTION)
    tbl = copy.deepcopy(d.tables[1]._tbl)
    caption.addnext(tbl)
    t4 = docx.table.Table(tbl, anchor._parent)
    table_rows(t4, TABLE4)
    set_widths(t4, [10.5, 2.5, 3.5])
    for (ti, ri), cells in CELLS.items():
        row = d.tables[ti].rows[ri]
        for cell, text in zip(row.cells, cells):
            if text is not None:
                set_text(cell.paragraphs[0], text)
                for extra in cell.paragraphs[1:]:
                    extra._p.getparent().remove(extra._p)
    for p in d.paragraphs:
        head = p.text.split("\t")[0]
        if "\t" in p.text and head in TOC_PAGES:
            p._p.findall(".//" + qn("w:t"))[-1].text = TOC_PAGES[head]
    replace_figure(d)
    d.save(dst)
    print(dst, f"абзацев: {len(done)}, заголовков: {len(HEADINGS)}, строк таблицы 2: {len(TABLE2) - 1}")


