def set_widths(table, cm: list[float]) -> None:
    """Ширины столбцов таблицы, см: в сетке таблицы и у каждой ячейки."""
    twips = [str(round(w * 567)) for w in cm]
    grid = table._tbl.find(qn("w:tblGrid"))
    for col, w in zip(grid.findall(qn("w:gridCol")), twips):
        col.set(qn("w:w"), w)
    for row in table.rows:
        for cell, w in zip(row.cells, twips):
            tcpr = cell._tc.get_or_add_tcPr()
            tcw = tcpr.find(qn("w:tcW"))
            if tcw is None:
                tcw = etree.SubElement(tcpr, qn("w:tcW"))
            tcw.set(qn("w:w"), w)
            tcw.set(qn("w:type"), "dxa")


def table4() -> list[list[str]]:
    import json

