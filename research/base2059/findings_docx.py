def n(x: float | int) -> str:
    s = f"{x:,}".replace(",", " ") if isinstance(x, int) else f"{x}".replace(".", ",")
    return s


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}".replace(".", ",") + " %"


