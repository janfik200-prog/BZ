"""Агент-паспортизатор: геологический смысл признаков базы.

Механическую часть паспортов заполняет `db_fill_passports.py` — покрытие,
циркулярность, переносимость. Смысл признака оттуда не берётся: из данных он
не выводится. Этот агент собирает по каждому признаку факты (источник, способ
расчёта, покрытие, статистику значений), спрашивает языковую модель и пишет
черновик в `meta.feature_passport`.

Запуск:
    python scripts/db_agent_passporter.py               — все без смысла
    python scripts/db_agent_passporter.py --сколько 5    — первые пять
    python scripts/db_agent_passporter.py --сухой        — показать задачу, не спрашивая
    python scripts/db_agent_passporter.py --сверка 8     — сверка с эталоном проекта
    python scripts/db_agent_passporter.py --провайдер локальный

Три правила, ради которых это агент, а не генератор текста:

* **модель не подтверждает.** Запись идёт со статусом «черновик»; статус
  «подтверждён» ставит человек, и база не даст обойти это триггером;
* **модель не списывает.** Предметные формулировки, накопленные в проекте
  (словарь признаков проекта, `src/feature_dict.geo_note`), на вход не подаются — иначе сверка
  «что модель поняла сама» бессмысленна. На вход идёт только техническое
  описание съёмки и факты из базы;
* **каждое обращение записано.** Модель, время ответа, токены, число попыток
  и сам ответ ложатся в `runs.llm_call`. Это же и площадка для перехода на
  локальную модель: тот же набор признаков прогоняется другим исполнителем и
  сравнивается по журналу.

Обращение к модели идёт через `gisdb/agent_llm.py` — единственную точку в
проекте, где выбирается облачная или локальная модель.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gisdb import agent_llm, db
from gisdb import db_ingest as ingest
from gisdb import feature_facts
from gisdb.feature_facts import задача, факты
from gisdb.project import подключить

подключить()                       # эталон сверки живёт в проекте
from src.feature_dict import geo_note      # noqa: E402

СКРИПТ = "scripts/db_agent_passporter.py"

# Ответ строго по этой схеме: в облаке она навязана инструментом, на локальном
# сервере — полем response_format, сверх того проверяется в agent_llm.
СХЕМА = {
    "type": "object",
    "properties": {
        "смысл": {
            "type": "string", "minLength": 80,
            "description": "Только предметно: что означают высокие и что низкие значения "
                           "признака для геологии участка и как это связано с поиском золота "
                           "и урана. Длины волн, формулы, способ усреднения и размер ячейки "
                           "сюда не пишутся — они уже есть в паспорте слоя",
        },
        "роль": {
            "type": "string",
            "enum": ["прямое измерение", "прокси", "фон", "служебный"],
            "description": "Прямо ли признак измеряет геологическое свойство или лишь косвенно",
        },
        "фактор": {
            "type": "string",
            "enum": [
                "структурный контроль", "гидротермальные изменения",
                "литологический контроль", "магматизм", "палеодолины и впадины",
                "обнажённость и растительный покров", "рельеф и геоморфология",
                "плотностная и магнитная неоднородность", "не установлен",
            ],
            "description": "К какому рудоконтролирующему фактору признак ближе всего",
        },
        "обоснование": {
            "type": "string", "minLength": 40,
            "description": "Почему выводу можно верить и насколько: из чего он следует "
                           "(природа измерения, известная методика) и что его ослабляет — "
                           "покрытие, зависимость от контура съёмки, замкнутый вывод",
        },
        "уверенность": {"type": "string", "enum": ["высокая", "средняя", "низкая"]},
    },
    "required": ["смысл", "роль", "фактор", "обоснование", "уверенность"],
    "additionalProperties": False,
}

РОЛЬ = """Ты геолог-эксперт по прогнозу рудных узлов и по дистанционным методам.
Ты заполняешь паспорт признака в базе данных проекта прогноза золото-урановых
рудных узлов на Анабарском щите (Якутия, архейско-протерозойский кристаллический
фундамент, перекрытый чехлом; рудоконтролирующая структура района — зона
тектонического меланжа северо-западного простирания).

Правила:
1. Опирайся только на приведённые факты о признаке и на общее знание о физике
   съёмки и способах расчёта. Не придумывай данных, которых в фактах нет.
2. Различай прямое измерение геологического свойства и косвенный показатель.
   Не утверждай связь с золотом или ураном, если она не следует из природы
   измерения; предположение называй предположением.
3. Техническое описание съёмки и способ расчёта уже записаны в базе, в паспорте
   слоя-источника. Не пересказывай их: в поле «смысл» идёт только предметное —
   что высокие и что низкие значения признака говорят о геологии участка.
4. Если признак самостоятельного геологического смысла не имеет (сырой канал
   съёмки, доля наблюдений, техническая маска) — скажи это прямо одной фразой и
   добавь, чем он может быть полезен косвенно или почему бесполезен. Это
   нормальный ответ, а не неудача, но заменять его пересказом техники нельзя.
5. Пиши по-русски, простыми терминами, без англоязычных калек. Длина смысла —
   2-4 предложения.
6. Уверенность «высокая» — только когда смысл следует из самой природы
   измерения; если вывод построен на аналогии — «средняя» или «низкая»."""


# ------------------------------------------------------------------- выборка
# Сбор фактов и текст задачи вынесены в gisdb/feature_facts.py: панель
# подтверждений показывает человеку ровно то, что видела модель.
ОТБОР = """WHERE p.status = 'черновик' AND (p.geological_meaning IS NULL OR %s)"""


# -------------------------------------------------------------------- запись
ОБНОВЛЕНИЕ = """
UPDATE meta.feature_passport
   SET geological_meaning = %s, kb_reference = %s, model = %s
 WHERE feature_id = %s AND status = 'черновик'
"""


def записать(conn, run_id: int, ф: dict, ответ: agent_llm.Answer, модель: str) -> None:
    """Черновик паспорта, ребро происхождения и гипотеза для базы знаний."""
    д = ответ.data
    обоснование = (
        f"{д['обоснование']} — вывод агента (уверенность: {д['уверенность']}, "
        f"роль признака: {д['роль']}); публикация не привязана, "
        f"база знаний в разработке."
    )
    conn.execute(ОБНОВЛЕНИЕ, (д["смысл"], обоснование, модель, ф["id"]))

    op_id = conn.execute(
        """INSERT INTO meta.operation (kind, script, git_commit, params, run_id)
           VALUES ('паспортизация признака', %s, %s, %s, %s) RETURNING id""",
        (СКРИПТ, ingest.git_commit(),
         json.dumps({"модель": модель, "провайдер": ответ.provider,
                     "уверенность": д["уверенность"], "фактор": д["фактор"],
                     "попыток": ответ.attempts}, ensure_ascii=False),
         run_id),
    ).fetchone()[0]
    conn.execute(
        """INSERT INTO meta.derivation
               (operation_id, source_kind, source_id, target_kind, target_id)
           VALUES (%s, 'признак', %s, 'паспорт', %s)""",
        (op_id, ф["id"], ф["id"]),
    )

    # Мост к базе знаний: «признак относится к такому-то рудному фактору» —
    # гипотеза агента, а не справочник. Подтверждает человек.
    if д["фактор"] != "не установлен":
        есть = conn.execute(
            """SELECT 1 FROM bridge.feature_concept
                WHERE feature_id = %s AND concept_code = %s LIMIT 1""",
            (ф["id"], д["фактор"]),
        ).fetchone()
        if not есть:
            conn.execute(
                """INSERT INTO bridge.feature_concept
                       (feature_id, concept_code, role, origin, evidence_ref, run_id, note)
                   VALUES (%s, %s, %s, 'наш результат', %s, %s, %s)""",
                (ф["id"], д["фактор"],
                 "прямой" if д["роль"] == "прямое измерение" else "прокси",
                 f"обоснование агента, уверенность {д['уверенность']}",
                 run_id, д["обоснование"]),
            )


# --------------------------------------------------------------------- обход
def выбрать(conn, перезаписать: bool) -> list[dict]:
    return feature_facts.выбрать(conn, ОТБОР, (перезаписать,))


def по_кодам(записи: list[dict]) -> dict[str, list[dict]]:
    """Один код — один вопрос модели: смысл признака от сборки не зависит."""
    сгруппировано: dict[str, list[dict]] = {}
    for з in записи:
        сгруппировано.setdefault(з["code"], []).append(з)
    return сгруппировано


def main(argv: list[str]) -> None:
    сухой = "--сухой" in argv
    перезаписать = "--перезаписать" in argv

    def аргумент(имя: str, умолчание=None):
        return argv[argv.index(имя) + 1] if имя in argv else умолчание

    сколько = int(аргумент("--сколько", 0) or 0)
    сверка = int(аргумент("--сверка", 0) or 0)
    провайдер = аргумент("--провайдер")
    имя_модели = аргумент("--модель")

    with db.connect("gis_agent") as conn:
        записи = выбрать(conn, перезаписать or bool(сверка))
        группы = по_кодам(записи)

        if сверка:
            # Признаки, для которых в проекте уже есть формулировка эксперта:
            # на них видно, что модель понимает сама, а что придумывает.
            группы = {
                код: строки for код, строки in группы.items()
                if not geo_note(код, строки[0]["group_code"] or "").startswith(
                    "прямой геологической интерпретации не установлено")
            }
        коды = list(группы)[: сколько or None][: сверка or None]
        if not коды:
            print("описывать нечего: у всех признаков смысл уже записан "
                  "(в очереди к человеку он ждёт подтверждения)")
            return

        if сухой:
            ф = факты(conn, группы[коды[0]][0])
            print(РОЛЬ, "\n\n--- задача ---\n", задача(ф), sep="")
            print(f"\nразмер задачи: {agent_llm.estimate_tokens(РОЛЬ + задача(ф))} токенов "
                  f"при пределе {agent_llm.CONTEXT_TOKENS}")
            print(f"признаков к обработке: {len(группы)} кодов, {len(записи)} паспортов")
            return

        модель = agent_llm.Model(provider=провайдер, model=имя_модели)
        print(f"исполнитель: {модель}; кодов к обработке: {len(коды)}", flush=True)

        with ingest.run(
            conn, script=СКРИПТ, model=str(модель),
            note=f"смысл признаков: {len(коды)} кодов"
                 + (" (сверка с эталоном, без записи)" if сверка else ""),
        ) as run_id:
            готово = сбои = 0
            прерван = False
            токенов_вход = токенов_выход = миллисекунд = попыток = 0
            низкая = 0

            for i, код in enumerate(коды, 1):
                ф = факты(conn, группы[код][0])
                текст = задача(ф)
                try:
                    ответ = модель.ask(РОЛЬ, текст, СХЕМА)
                except agent_llm.ОтказИсполнителя as отказ:
                    # Исполнитель молчит не про этот признак, а вообще: идти
                    # дальше по очереди — только терять её впустую. Прогон
                    # закрывается, остаток доберёт повторный запуск.
                    agent_llm.log_call(conn, run_id, None, "смысл признака", код,
                                       model=модель, error=str(отказ)[:500])
                    conn.commit()
                    прерван = True
                    print(f"[{i}/{len(коды)}] {код}: исполнитель отказал — {отказ}",
                          flush=True)
                    break
                except Exception as ошибка:
                    сбои += 1
                    agent_llm.log_call(conn, run_id, None, "смысл признака", код,
                                       model=модель, error=str(ошибка)[:500])
                    conn.commit()
                    print(f"[{i}/{len(коды)}] {код}: сбой — {ошибка}", flush=True)
                    continue

                agent_llm.log_call(conn, run_id, ответ, "смысл признака", код)
                токенов_вход += ответ.in_tokens
                токенов_выход += ответ.out_tokens
                миллисекунд += ответ.latency_ms
                попыток += ответ.attempts
                низкая += ответ.data["уверенность"] == "низкая"

                if сверка:
                    эталон = geo_note(код, ф["группа"])
                    print(f"\n[{i}/{len(коды)}] {код}")
                    print(f"  эталон проекта: {эталон}")
                    print(f"  ответ агента:   {ответ.data['смысл']}")
                    print(f"  фактор: {ответ.data['фактор']}; "
                          f"роль: {ответ.data['роль']}; "
                          f"уверенность: {ответ.data['уверенность']}", flush=True)
                else:
                    for запись in группы[код]:
                        записать(conn, run_id, {**ф, "id": запись["id"]}, ответ, str(модель))
                    print(f"[{i}/{len(коды)}] {код}: {ответ.data['фактор']}, "
                          f"уверенность {ответ.data['уверенность']}, "
                          f"паспортов {len(группы[код])}, "
                          f"{ответ.latency_ms} мс", flush=True)
                готово += 1
                conn.commit()

            ingest.add_metric(conn, run_id, "признаков описано", готово)
            ingest.add_metric(conn, run_id, "прогон прерван", int(прерван))
            ingest.add_metric(conn, run_id, "сбоев модели", сбои)
            ingest.add_metric(conn, run_id, "токенов на входе", токенов_вход)
            ingest.add_metric(conn, run_id, "токенов на выходе", токенов_выход)
            if готово:
                ingest.add_metric(conn, run_id, "среднее время ответа, мс", миллисекунд / готово)
                ingest.add_metric(conn, run_id, "попыток на ответ", попыток / готово)
                ingest.add_metric(conn, run_id, "доля низкой уверенности", низкая / готово)
            conn.commit()

            осталось = conn.execute(
                "SELECT count(*) FROM meta.feature_passport WHERE geological_meaning IS NULL"
            ).fetchone()[0]
            print(f"\nпрогон #{run_id}: описано {готово}, сбоев {сбои}, "
                  f"без смысла осталось {осталось}; "
                  f"токенов {токенов_вход}+{токенов_выход}")
            if прерван:
                print("прогон прерван отказом исполнителя: повторный запуск "
                      "возьмёт только то, что осталось без смысла")


if __name__ == "__main__":
    main(sys.argv[1:])
